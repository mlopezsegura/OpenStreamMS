"""Generate the installer language table and custom messages from checked-in JSON.

Uses only the Python standard library. Does not download, install or start anything.
"""
from pathlib import Path
import json, re

root = Path(__file__).resolve().parents[1]
installer = root / 'Core/Installer'
codes = json.loads((root / 'Core/Localization/locales.json').read_text(encoding='utf-8'))['locales']
official = {'bg':'Bulgarian','cs':'Czech','de':'German','es':'Spanish','fr':'French','hu':'Hungarian','it':'Italian','ja':'Japanese','ko':'Korean','pl':'Polish','pt':'Portuguese','pt_BR':'BrazilianPortuguese','ru':'Russian','sv':'Swedish','tr':'Turkish','uk':'Ukrainian'}
names = {'en':'english','en_US':'americanenglish','en_GB':'britishenglish', 'zh':'chinesesimplified','zh_TW':'chinesetraditional','vi':'vietnamese', **{code:name.lower() for code,name in official.items()}}
vendor = {'en_GB':'EnglishBritish','zh':'ChineseSimplified','zh_TW':'ChineseTraditional','vi':'Vietnamese'}
langlines = []
for code in ['en'] + [c for c in codes if c != 'en']:
    resource = 'compiler:Languages\\'+official[code]+'.isl' if code in official else 'Languages\\'+vendor[code]+'.isl' if code in vendor else 'compiler:Default.isl'
    if code in ('en','en_US'):
        resource += ',Languages\\English'+('Neutral' if code=='en' else 'US')+'.isl'
    langlines.append(f'Name: "{names[code]}"; MessagesFile: "{resource}"')
messages = []
english = json.loads((installer/'messages/en.json').read_text(encoding='utf-8'))
for code in codes:
    table = json.loads((installer/f'messages/{code}.json').read_text(encoding='utf-8'))
    assert table.keys() == english.keys(), code
    for key, value in table.items():
        assert sorted(re.findall(r'%[n1-9]|\{[^}]+\}',value)) == sorted(re.findall(r'%[n1-9]|\{[^}]+\}',english[key])), (code,key)
        # The .isl format is line based. Provider-added wrapping is whitespace,
        # while deliberate installer line breaks remain the protected %n tokens.
        value = ' '.join(value.splitlines())
        messages.append(f'{names[code]}.{key}={value}')
for suffix, title, lid in [('Neutral','English','$0009'),('US','English (United States)','$0409')]:
    (installer/f'Languages/English{suffix}.isl').write_text(f'; OpenStreamMS English region metadata; standard messages inherit compiler:Default.isl\n[LangOptions]\nLanguageName={title}\nLanguageID={lid}\n',encoding='utf-8')
(installer/'languages.generated.iss').write_text('; Generated by tools/generate-installer-locales.py\n'+'\n'.join(langlines)+'\n',encoding='utf-8')
(installer/'messages.generated.iss').write_text('; Generated by tools/generate-installer-locales.py\n'+'\n'.join(messages)+'\n',encoding='utf-8')
script = installer/'setup.iss'
text = script.read_text(encoding='utf-8')
text = re.sub(r'(?s)\[Languages\].*?\[CustomMessages\].*?(?=\[Tasks\])','[Languages]\n#include "languages.generated.iss"\n\n[CustomMessages]\n#include "messages.generated.iss"\n\n',text)
script.write_text(text,encoding='utf-8')
print(f'Generated {len(codes)} installer languages and {len(messages)} custom messages')
