const SUPPORTED   = ['en', 'es', 'fr', 'pt'];
const DEFAULT_LANG = 'en';
const STORAGE_KEY  = 'openstreamms.lang';

function detectLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && SUPPORTED.includes(stored)) return stored;
  } catch { /* privacy mode */ }
  const nav = (navigator.language || '').slice(0, 2).toLowerCase();
  return SUPPORTED.includes(nav) ? nav : DEFAULT_LANG;
}

const I18n = {
  lang: detectLanguage(),

  t(key, params) {
    const table = MESSAGES[this.lang] || MESSAGES[DEFAULT_LANG];
    let val = table[key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
    if (params) for (const k in params) val = val.split(`{${k}}`).join(params[k]);
    return val;
  },

  setLanguage(lang) {
    if (!SUPPORTED.includes(lang) || lang === this.lang) return;
    this.lang = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
    document.documentElement.lang = lang;
    this.apply();
    window.dispatchEvent(new Event('langchange'));
  },

  apply(root) {
    const r = root || document;
    r.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = this.t(el.dataset.i18n);
    });
    r.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = this.t(el.dataset.i18nHtml);
    });
    r.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.dataset.i18nPlaceholder);
    });
    r.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.dataset.i18nTitle);
    });

    const docTitleKey = document.documentElement.dataset.i18nDocTitle;
    if (docTitleKey) document.title = this.t(docTitleKey);

    document.documentElement.lang = this.lang;
    const sel = document.getElementById('lang-select');
    if (sel && sel.value !== this.lang) sel.value = this.lang;
  },

  supported() { return SUPPORTED.slice(); },
};

window.I18n  = I18n;
window.t     = (k, p) => I18n.t(k, p);

document.addEventListener('DOMContentLoaded', () => {
  // Rellenar el selector de idioma si existe
  const sel = document.getElementById('lang-select');
  if (sel) {
    sel.innerHTML = SUPPORTED.map(l =>
      `<option value="${l}">${MESSAGES[l]['lang.' + l]}</option>`).join('');
    sel.value = I18n.lang;
    sel.addEventListener('change', () => I18n.setLanguage(sel.value));
  }
  I18n.apply();
});
